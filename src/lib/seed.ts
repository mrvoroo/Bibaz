import type { Product, SizeOption, StoreData, FlavorKey, L10n } from "./types";

const SERVES = { 15: "4-6", 20: "8-10", 25: "12-14", 30: "16-20" } as const;

function sizes(p15: number, p20: number, p25: number, p30: number): SizeOption[] {
  return ([15, 20, 25, 30] as const).map((cm, i) => ({
    cm,
    serves: SERVES[cm],
    price: [p15, p20, p25, p30][i],
    stock: 20,
    enabled: true,
  }));
}

